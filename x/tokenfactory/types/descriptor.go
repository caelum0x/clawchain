package types

// This file gives the hand-written tokenfactory message types (see msgs.go) a
// real protobuf FileDescriptor. Two things require it:
//
//  1. Tx decode: cosmos-sdk's unknownproto.RejectUnknownFields calls msg.Descriptor()
//     to map field tags -> types and reject unknown fields. Without a Descriptor()
//     method the standard tx codec fails with
//     "*types.MsgCreateDenom does not have a Descriptor() method", so the messages
//     could be dispatched by CosmWasm (Stargate) but never submitted as signed txs
//     (e.g. via the CLI).
//
//  2. Signer resolution: the registered FileDescriptor carries the
//     (cosmos.msg.v1.signer) = "sender" option for each Msg, which the ante handler's
//     signing context uses to determine the expected signer.
//
// The struct definitions and their Marshal/Unmarshal stay hand-written in msgs.go
// (and remain wire-compatible with cosmos.base.v1beta1.Coin), so this file only adds
// the descriptor bytes, the file registration, and the per-message Descriptor()
// methods. The bytes below are generated from proto/osmosis/tokenfactory/v1beta1/tx.proto.
//
// To regenerate after editing that .proto (it lives outside proto/clawchain so the
// repo-wide `make proto-gen` does not touch it):
//
//	mv buf.lock .tmp/buf.lock.bak
//	go tool github.com/bufbuild/buf/cmd/buf generate proto \
//	  --config buf.local.yaml --template proto/buf.gen.gogo.yaml \
//	  --path proto/osmosis/tokenfactory/v1beta1/tx.proto
//	mv .tmp/buf.lock.bak buf.lock
//
// then copy the fileDescriptor bytes and Descriptor() methods from
// clawchain/x/tokenfactory/types/tx.pb.go into this file.


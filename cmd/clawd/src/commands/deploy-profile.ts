/**
 * `clawd deploy-profile` — generate deployment configuration for different targets.
 *
 * Targets: local, vps, docker, k8s
 */

import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export type DeployProfileOptions = {
  target: "local" | "vps" | "k8s" | "docker";
  output?: string;
  json?: boolean;
  moniker?: string;
  chainId?: string;
  rpcPort?: string;
  restPort?: string;
};

type ProfileResult = {
  target: string;
  files: { name: string; content: string }[];
};

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

function defaults(opts: DeployProfileOptions) {
  return {
    moniker: opts.moniker ?? "clawchain-node",
    chainId: opts.chainId ?? "clawchain-1",
    rpcPort: opts.rpcPort ?? "26657",
    restPort: opts.restPort ?? "1317",
  };
}

// ---------------------------------------------------------------------------
// Local profile
// ---------------------------------------------------------------------------

function generateLocal(opts: DeployProfileOptions): ProfileResult {
  const d = defaults(opts);

  const config = JSON.stringify(
    {
      chainId: d.chainId,
      rpcUrl: `http://localhost:${d.rpcPort}`,
      restUrl: `http://localhost:${d.restPort}`,
      nodeAutoStart: true,
      nodeHome: "",
      moniker: d.moniker,
      denom: "uclaw",
      prefix: "claw",
      gasPrice: "0.025uclaw",
    },
    null,
    2,
  );

  const script = `#!/bin/bash
# ClawChain Local Provider Setup
# Generated by: clawd deploy-profile --target local
set -euo pipefail

echo "Starting ClawChain local environment..."
echo "  Moniker:  ${d.moniker}"
echo "  Chain ID: ${d.chainId}"
echo "  RPC:      http://localhost:${d.rpcPort}"
echo "  REST:     http://localhost:${d.restPort}"

# Start the chain node in the background
clawchaind start --home ~/.clawchain \\
  --rpc.laddr tcp://0.0.0.0:${d.rpcPort} \\
  --api.address tcp://0.0.0.0:${d.restPort} &
CHAIN_PID=$!

# Wait for the chain to become healthy
echo "Waiting for chain node..."
for i in $(seq 1 30); do
  if curl -sf http://localhost:${d.rpcPort}/health > /dev/null 2>&1; then
    echo "Chain node is healthy."
    break
  fi
  sleep 2
done

# Start clawd
clawd up

# Cleanup on exit
trap "kill $CHAIN_PID 2>/dev/null" EXIT
wait $CHAIN_PID
`;

  return {
    target: "local",
    files: [
      { name: "clawd.json", content: config },
      { name: "start-local.sh", content: script },
    ],
  };
}

// ---------------------------------------------------------------------------
// VPS profile
// ---------------------------------------------------------------------------

function generateVps(opts: DeployProfileOptions): ProfileResult {
  const d = defaults(opts);

  const clawchaindService = `[Unit]
Description=ClawChain Validator Node
Documentation=https://github.com/clawchain/clawchain
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
User=clawchain
Group=clawchain
ExecStart=/usr/local/bin/clawchaind start --home /var/lib/clawchain/.clawchain
ExecReload=/bin/kill -HUP $MAINPID
Restart=on-failure
RestartSec=10
StartLimitInterval=200
StartLimitBurst=5

# Logging
StandardOutput=journal
StandardError=journal
SyslogIdentifier=clawchaind

# Security hardening
NoNewPrivileges=true
PrivateTmp=true
ProtectSystem=strict
ProtectHome=true
ReadWritePaths=/var/lib/clawchain

# Resource limits
LimitNOFILE=65535
LimitNPROC=4096
MemoryMax=8G
CPUQuota=400%

# Environment
Environment="HOME=/var/lib/clawchain"
Environment="CHAIN_ID=${d.chainId}"
Environment="MONIKER=${d.moniker}"

[Install]
WantedBy=multi-user.target
`;

  const clawdService = `[Unit]
Description=ClawChain CLI Daemon (clawd)
Documentation=https://github.com/clawchain/clawchain
After=network-online.target clawchaind.service
Wants=network-online.target

[Service]
Type=simple
User=clawchain
Group=clawchain
ExecStart=/usr/bin/node /opt/clawd/dist/main.js up
Restart=on-failure
RestartSec=10
StartLimitInterval=200
StartLimitBurst=5

# Logging
StandardOutput=journal
StandardError=journal
SyslogIdentifier=clawd

# Environment
Environment="BLOCKCHAIN_RPC_URL=http://localhost:${d.rpcPort}"
Environment="BLOCKCHAIN_REST_URL=http://localhost:${d.restPort}"
Environment="BLOCKCHAIN_CHAIN_ID=${d.chainId}"
EnvironmentFile=-/etc/clawchain/clawd.env

# Security hardening
NoNewPrivileges=true
PrivateTmp=true
ProtectSystem=strict
ProtectHome=true
ReadWritePaths=/var/lib/clawchain

# Resource limits
LimitNOFILE=4096
MemoryMax=1G

[Install]
WantedBy=multi-user.target
`;

  const nginxConf = `# ClawChain Nginx Configuration
# Generated by: clawd deploy-profile --target vps

upstream clawchain_rpc {
    server 127.0.0.1:${d.rpcPort};
}

upstream clawchain_rest {
    server 127.0.0.1:${d.restPort};
}

upstream clawchain_grpc {
    server 127.0.0.1:9090;
}

server {
    listen 80;
    server_name _;

    # RPC endpoint
    location /rpc/ {
        proxy_pass http://clawchain_rpc/;
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
    }

    # REST/LCD endpoint
    location /api/ {
        proxy_pass http://clawchain_rest/;
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
    }

    # WebSocket for CometBFT
    location /websocket {
        proxy_pass http://clawchain_rpc/websocket;
        proxy_http_version 1.1;
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection "upgrade";
    }

    # Health check
    location /health {
        proxy_pass http://clawchain_rpc/health;
    }

    # TLS placeholder — replace with your certificate paths
    # listen 443 ssl;
    # ssl_certificate /etc/letsencrypt/live/YOUR_DOMAIN/fullchain.pem;
    # ssl_certificate_key /etc/letsencrypt/live/YOUR_DOMAIN/privkey.pem;
}
`;

  const firewallRules = `#!/bin/bash
# ClawChain UFW Firewall Rules
# Generated by: clawd deploy-profile --target vps
set -euo pipefail

echo "Configuring firewall rules for ClawChain VPS..."

# Reset UFW (optional — uncomment if you want a clean slate)
# ufw --force reset

# Default policies
ufw default deny incoming
ufw default allow outgoing

# SSH (always allow)
ufw allow 22/tcp comment "SSH"

# CometBFT P2P (required for peer connections)
ufw allow 26656/tcp comment "CometBFT P2P"

# CometBFT RPC (optional — expose only if needed externally)
ufw allow ${d.rpcPort}/tcp comment "CometBFT RPC"

# REST/LCD API (optional — expose only if needed externally)
ufw allow ${d.restPort}/tcp comment "REST API"

# gRPC (optional — expose only if needed externally)
ufw allow 9090/tcp comment "gRPC"

# HTTP/HTTPS for Nginx
ufw allow 80/tcp comment "HTTP"
ufw allow 443/tcp comment "HTTPS"

# Enable UFW
ufw --force enable

echo "Firewall configured. Active rules:"
ufw status verbose
`;

  return {
    target: "vps",
    files: [
      { name: "clawchaind.service", content: clawchaindService },
      { name: "clawd.service", content: clawdService },
      { name: "nginx-clawchain.conf", content: nginxConf },
      { name: "setup-firewall.sh", content: firewallRules },
    ],
  };
}


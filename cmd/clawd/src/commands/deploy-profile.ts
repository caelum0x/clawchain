function generateDocker(opts: DeployProfileOptions): ProfileResult {
  const d = defaults(opts);

  const compose = `##
## ClawChain Docker Compose — Essential Services
## Generated by: clawd deploy-profile --target docker
##
## Usage:
##   docker compose -f docker-compose.clawchain.yml up -d
##   docker compose -f docker-compose.clawchain.yml logs -f clawchain
##   docker compose -f docker-compose.clawchain.yml down
##

services:
  # -- ClawChain Node --------------------------------------------------------
  clawchain:
    build:
      context: .
      dockerfile: Dockerfile
    container_name: clawchain-node
    ports:
      - "${d.rpcPort}:26657"    # CometBFT RPC
      - "${d.restPort}:1317"    # REST API
      - "9090:9090"             # gRPC
      - "26660:26660"           # Prometheus metrics
    volumes:
      - clawchain-data:/root/.clawchain
    environment:
      - CHAIN_ID=${d.chainId}
      - MONIKER=${d.moniker}
    healthcheck:
      test: ["CMD", "curl", "-f", "http://localhost:26657/health"]
      interval: 10s
      timeout: 5s
      retries: 12
      start_period: 15s
    networks:
      - clawnet
    restart: unless-stopped
    deploy:
      resources:
        limits:
          memory: 8G
          cpus: "4.0"
        reservations:
          memory: 2G
          cpus: "1.0"

  # -- clawd Agent -----------------------------------------------------------
  clawd:
    build:
      context: ./cmd/clawd
      dockerfile: Dockerfile
    container_name: clawchain-clawd
    environment:
      - BLOCKCHAIN_RPC_URL=http://clawchain:26657
      - BLOCKCHAIN_REST_URL=http://clawchain:1317
      - BLOCKCHAIN_CHAIN_ID=${d.chainId}
      - BLOCKCHAIN_AUTONOMOUS_LOOP_ENABLED=true
    depends_on:
      clawchain:
        condition: service_healthy
    networks:
      - clawnet
    restart: unless-stopped
    deploy:
      resources:
        limits:
          memory: 1G
          cpus: "1.0"

  # -- Token Faucet ----------------------------------------------------------
  claw-faucet:
    build:
      context: .
      dockerfile: cmd/claw-faucet/Dockerfile
    container_name: clawchain-faucet
    ports:
      - "8888:8888"
    environment:
      - CHAIN_REST=http://clawchain:1317
      - CHAIN_RPC=http://clawchain:26657
      - CHAIN_ID=${d.chainId}
      - FAUCET_MNEMONIC=REPLACE_WITH_FAUCET_MNEMONIC
      - FAUCET_AMOUNT=10000000
    depends_on:
      clawchain:
        condition: service_healthy
    healthcheck:
      test: ["CMD", "curl", "-f", "http://localhost:8888/health"]
      interval: 10s
      timeout: 5s
      retries: 5
      start_period: 10s
    networks:
      - clawnet
    restart: unless-stopped
    deploy:
      resources:
        limits:
          memory: 512M
          cpus: "0.5"

networks:
  clawnet:
    driver: bridge

volumes:
  clawchain-data:
`;

  return {
    target: "docker",
    files: [
      { name: "docker-compose.clawchain.yml", content: compose },
    ],
  };
}


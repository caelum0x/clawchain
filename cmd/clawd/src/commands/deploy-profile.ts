function generateK8s(opts: DeployProfileOptions): ProfileResult {
  const d = defaults(opts);

  const namespace = `apiVersion: v1
kind: Namespace
metadata:
  name: clawchain
  labels:
    app.kubernetes.io/part-of: clawchain
    app.kubernetes.io/managed-by: clawd
`;

  const configmap = `apiVersion: v1
kind: ConfigMap
metadata:
  name: clawchain-config
  namespace: clawchain
  labels:
    app.kubernetes.io/part-of: clawchain
data:
  CHAIN_ID: "${d.chainId}"
  MONIKER: "${d.moniker}"
  RPC_PORT: "${d.rpcPort}"
  REST_PORT: "${d.restPort}"
  GRPC_PORT: "9090"
  P2P_PORT: "26656"
  PROMETHEUS_PORT: "26660"
`;

  const deployment = `apiVersion: apps/v1
kind: Deployment
metadata:
  name: clawchain-node
  namespace: clawchain
  labels:
    app: clawchain-node
    app.kubernetes.io/part-of: clawchain
spec:
  replicas: 1
  selector:
    matchLabels:
      app: clawchain-node
  template:
    metadata:
      labels:
        app: clawchain-node
    spec:
      securityContext:
        runAsNonRoot: true
        runAsUser: 1000
        fsGroup: 1000
      containers:
        - name: clawchaind
          image: clawchain/clawchaind:latest
          ports:
            - containerPort: 26657
              name: rpc
            - containerPort: 1317
              name: rest
            - containerPort: 9090
              name: grpc
            - containerPort: 26656
              name: p2p
            - containerPort: 26660
              name: metrics
          envFrom:
            - configMapRef:
                name: clawchain-config
          resources:
            requests:
              memory: "2Gi"
              cpu: "1000m"
            limits:
              memory: "8Gi"
              cpu: "4000m"
          livenessProbe:
            httpGet:
              path: /health
              port: 26657
            initialDelaySeconds: 30
            periodSeconds: 10
            timeoutSeconds: 5
            failureThreshold: 3
          readinessProbe:
            httpGet:
              path: /health
              port: 26657
            initialDelaySeconds: 15
            periodSeconds: 5
            timeoutSeconds: 3
            failureThreshold: 5
          volumeMounts:
            - name: chain-data
              mountPath: /root/.clawchain
      volumes:
        - name: chain-data
          persistentVolumeClaim:
            claimName: clawchain-data
---
apiVersion: v1
kind: PersistentVolumeClaim
metadata:
  name: clawchain-data
  namespace: clawchain
spec:
  accessModes:
    - ReadWriteOnce
  resources:
    requests:
      storage: 100Gi
`;

  const service = `apiVersion: v1
kind: Service
metadata:
  name: clawchain-node
  namespace: clawchain
  labels:
    app: clawchain-node
    app.kubernetes.io/part-of: clawchain
spec:
  selector:
    app: clawchain-node
  ports:
    - name: rpc
      port: ${d.rpcPort}
      targetPort: 26657
      protocol: TCP
    - name: rest
      port: ${d.restPort}
      targetPort: 1317
      protocol: TCP
    - name: grpc
      port: 9090
      targetPort: 9090
      protocol: TCP
    - name: p2p
      port: 26656
      targetPort: 26656
      protocol: TCP
    - name: metrics
      port: 26660
      targetPort: 26660
      protocol: TCP
  type: ClusterIP
`;

  return {
    target: "k8s",
    files: [
      { name: "namespace.yaml", content: namespace },
      { name: "configmap.yaml", content: configmap },
      { name: "deployment.yaml", content: deployment },
      { name: "service.yaml", content: service },
    ],
  };
}

// ---------------------------------------------------------------------------
// Profile dispatch
// ---------------------------------------------------------------------------

const generators: Record<string, (opts: DeployProfileOptions) => ProfileResult> = {
  local: generateLocal,
  vps: generateVps,
  docker: generateDocker,
  k8s: generateK8s,
};

// ---------------------------------------------------------------------------
// Public entry point
// ---------------------------------------------------------------------------

export async function runDeployProfile(opts: DeployProfileOptions): Promise<void> {
  const gen = generators[opts.target];
  if (!gen) {
    console.error(`Unknown target: ${opts.target}. Valid targets: local, vps, docker, k8s`);
    process.exitCode = 1;
    return;
  }

  const result = gen(opts);

  // JSON mode — emit the entire result as structured JSON
  if (opts.json) {
    process.stdout.write(JSON.stringify(result, null, 2) + "\n");
    return;
  }

  // Output to directory
  if (opts.output) {
    mkdirSync(opts.output, { recursive: true });
    for (const file of result.files) {
      const filePath = join(opts.output, file.name);
      writeFileSync(filePath, file.content);
      console.log(`  wrote ${filePath}`);
    }
    console.log(`\nDeploy profile "${opts.target}" written to ${opts.output}/`);
    return;
  }

  // Default: print to stdout
  for (const file of result.files) {
    console.log(`# --- ${file.name} ---`);
    console.log(file.content);
  }
}
